function makeWords(start: number, end: number, text: string) {
  const tokens = text.trim().split(/\s+/).filter(Boolean);
  const step = Math.max(0.1, (end - start) / Math.max(1, tokens.length));
  return tokens.map((word, idx) => ({
    word,
    start: Number((start + idx * step).toFixed(2)),
    end: Number((start + (idx + 1) * step).toFixed(2)),
  }));
}

function buildSegments(raw: Array<[number, number, string]>) {
  return raw.map(([start, end, text]) => ({
    start,
    end,
    text,
    words: makeWords(start, end, text),
  }));
}

